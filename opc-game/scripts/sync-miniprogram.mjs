import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { resolve } from 'node:path'

const root = resolve(import.meta.dirname, '..')
const corePath = resolve(root, 'packages/game-core/src/index.ts')
const contentPath = resolve(root, 'content/quiz-v2.json')
const outputDir = resolve(root, 'miniprogram/generated')
const generatedCorePath = resolve(outputDir, 'game-core.ts')
const generatedContentPath = resolve(outputDir, 'quiz-v2.ts')
const checkOnly = process.argv.includes('--check')

const [coreSource, quizJson] = await Promise.all([
  readFile(corePath, 'utf8'),
  readFile(contentPath, 'utf8'),
])
const quiz = JSON.parse(quizJson)
const generatedContent = `// Generated by scripts/sync-miniprogram.mjs. Do not edit.\nimport type { QuizDefinition } from './game-core'\n\nexport const quizDefinition: QuizDefinition = ${JSON.stringify(quiz, null, 2)}\n`

await mkdir(outputDir, { recursive: true })

if (checkOnly) {
  const [currentCore, currentContent] = await Promise.all([
    readFile(generatedCorePath, 'utf8').catch(() => ''),
    readFile(generatedContentPath, 'utf8').catch(() => ''),
  ])
  if (currentCore !== coreSource || currentContent !== generatedContent) {
    console.error('Generated mini-program modules are stale. Run npm run sync:mini.')
    process.exitCode = 1
  } else {
    console.log('Mini-program generated modules are current.')
  }
} else {
  await Promise.all([
    writeFile(generatedCorePath, coreSource),
    writeFile(generatedContentPath, generatedContent),
  ])
  console.log(`Synced game core and ${quiz.questions.length} v2 questions into miniprogram/generated/.`)
}
